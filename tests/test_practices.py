class SearchTest(PracticesCase):
    def populate(self):
        self.write("dns-ttl", entry_text(body="The resolver caches answers for their TTL.\n"))
        self.write("cache-flush", entry_text(
            {"id": "cache-flush", "tags": "[cache, ops]", "durability": "durable", "recheck": None},
            body="Flush the cache after a deploy. The cache is shared; flush it twice.\n"))
        self.write("backups", entry_text({"id": "backups", "tags": "[backup]"}, body="Nightly archives.\n"))

    def test_search(self):
        self.populate()
        found = lambda *terms: [e.id for e in practices.search(self.entries(), list(terms))]
        self.assertEqual(found("ttl"), ["dns-ttl"])
        self.assertEqual(found("TTL"), ["dns-ttl"])  # case-insensitive
        self.assertEqual(found("backup"), ["backups"])  # a tag
        self.assertEqual(found("flush", "cache"), ["cache-flush"])  # all terms must match
        self.assertEqual(found("flush", "ttl"), [])
        self.assertEqual(found("nothing-like-this"), [])
        self.assertEqual(found(), [])
        self.assertEqual(found("dns-ttl"), ["dns-ttl"])  # the id
        # Ranked by hits: "cache" appears in cache-flush's id, tags and body (4 times) and once in dns-ttl.
        self.assertEqual(found("cache"), ["cache-flush", "dns-ttl"])

    def test_search_command_marks_volatile_entries(self):
        self.populate()
        r = self.run_brain(self.root, "practices", "search", "resolver")
        self.assertEqual((r.returncode, r.stderr), (0, ""))
        lines = r.stdout.splitlines()
        self.assertEqual(lines[0], "dns-ttl: reliable, volatile, verified 2026-10-01")
        self.assertIn("  The resolver caches answers for their TTL.", lines)
        self.assertIn("  volatile: run dig +noall +answer example.com first", lines)

        r = self.run_brain(self.root, "practices", "search", "flush", "deploy")
        self.assertEqual(r.returncode, 0)
        self.assertIn("cache-flush: reliable, durable, verified 2026-10-01", r.stdout)
        self.assertNotIn("volatile:", r.stdout)

    def test_search_command_with_no_match(self):
        self.populate()
        r = self.run_brain(self.root, "practices", "search", "zzzz")
        self.assertEqual((r.returncode, r.stdout.strip()), (0, "no practice matches: zzzz"))

    def test_search_command_needs_a_term(self):
        self.assertEqual(self.run_brain(self.root, "practices", "search").returncode, 2)


class CliTest(PracticesCase):
    def test_practices_is_registered(self):
        self.assertIn("practices", cli.COMMANDS)
        r = self.run_brain(self.root, "practices", "--help")
        self.assertEqual(r.returncode, 0)
        for word in ("lint", "index", "candidates", "search"):
            self.assertIn(word, r.stdout)

    def test_subcommand_is_required(self):
        r = self.run_brain(self.root, "practices")
        self.assertEqual(r.returncode, 2)
        self.assertIn("usage: brain", r.stderr)

    def test_lint_exits_zero_when_clean(self):
        recent = (date.today() - timedelta(days=1)).isoformat()
        self.write("dns-ttl", entry_text({"verified": recent, "reproduced-by": f"watched it, {recent}"}))
        r = self.run_brain(self.root, "practices", "lint")
        self.assertEqual((r.returncode, r.stderr), (0, ""))
        self.assertEqual(r.stdout.splitlines()[-1], "practices lint: 1 checked, 0 blocking, 0 stale")

    def test_lint_exits_one_on_an_error(self):
        self.write("dns-ttl", entry_text({"evidence": "guessed", "verified": "2000-01-01"}))
        r = self.run_brain(self.root, "practices", "lint")
        self.assertEqual(r.returncode, 1)
        lines = r.stdout.splitlines()
        self.assertTrue(any(re.match(r"^BLOCK  docs/practices/dns-ttl\.md: evidence must be", l) for l in lines), lines)
        self.assertTrue(any(re.match(r"^WARN   docs/practices/dns-ttl\.md: ", l) for l in lines), lines)
        self.assertEqual(lines[-1], "practices lint: 1 checked, 1 blocking, 1 stale")

    def test_lint_exits_zero_when_only_stale(self):
        self.write("dns-ttl", entry_text({"verified": "2000-01-01", "reproduced-by": "watched it, 2000-01-01"}))
        r = self.run_brain(self.root, "practices", "lint")
        self.assertEqual((r.returncode, r.stderr), (0, ""))
        self.assertRegex(r.stdout, r"(?m)^WARN   docs/practices/dns-ttl\.md: ")
        self.assertEqual(r.stdout.splitlines()[-1], "practices lint: 1 checked, 0 blocking, 1 stale")

    def test_lint_exits_zero_with_no_practices(self):
        r = self.run_brain(self.root, "practices", "lint")
        self.assertEqual((r.returncode, r.stdout.splitlines()[-1]), (0, "practices lint: 0 checked, 0 blocking, 0 stale"))

    def test_lint_without_brain_json_fails_cleanly(self):
        (self.root / "brain.json").unlink()
        r = self.run_brain(self.root, "practices", "lint")
        self.assertEqual(r.returncode, 1)
        self.assertIn("brain.json", r.stderr)
        self.assertNotIn("Traceback", r.stderr)

    def test_commands_leave_the_nested_repo_index_alone(self):
        # Reading the store is file work only: no git process, so no .git/index is touched.
        self.git(self.root, "init", "-q")
        self.write("dns-ttl", entry_text())
        before = self.snapshot(self.root / ".git")
        for args in (["lint"], ["search", "ttl"], ["candidates", "--tags", "dns"], ["index", "--check"]):
            self.run_brain(self.root, "practices", *args)
        self.assertEqual(self.snapshot(self.root / ".git"), before)



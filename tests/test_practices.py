# A complete, valid entry at the strictest level (reliable, volatile): every conditional field is
# present, so removing or breaking any one of them produces exactly one finding.
BASE = {
    "id": "dns-ttl",
    "tags": "[dns, caching]",
    "durability": "volatile",
    "evidence": "reliable",
    "verified": "2026-10-01",
    "source": "resolver docs, issue 4521",
    "recheck": "dig +noall +answer example.com",
    "reproduced-by": "watched the TTL count down on two lookups, 2026-09-30",
    "reviewed-against": "[]",
}
BODY = "The resolver caches answers for their TTL.\n\nThe cache is per process.\n"


def entry_text(over=None, body=BODY, base=BASE) -> str:
    """The BASE entry with `over` applied; a value of None drops that field."""
    fields = dict(base)
    fields.update(over or {})
    lines = [f"{key}: {value}" for key, value in fields.items() if value is not None]
    return "---\n" + "\n".join(lines) + "\n---\n" + body



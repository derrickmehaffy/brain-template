FENCE = "`" * 3
CALL = "**Call it directly when:**"
DOCS = "docs/ROUTING.md"
META = "_meta/ROUTING-META.md"
BEGIN = "<!-- where:begin — generated by _meta/brain routing sync; do not edit -->"
END = "<!-- where:end -->"
HEADING = "## Where this sits"
TODO = "**Call it directly when:** TODO — say when someone should call this directly, and which earlier steps still apply."
GATE_NOTICE = ("**A gate on its path:** it runs every time, in any order with the other gates, including when it "
               "comes back clean. Record its result either way.")


def fenced(*lines: str) -> str:
    return "\n".join([FENCE + "mermaid", *lines, FENCE]) + "\n"


def block(*parts: str) -> str:
    """A generated block as `render_block` lays it out: markers around paragraphs, one blank line apart."""
    out = [BEGIN]
    for i, part in enumerate(parts):
        out += [part] if i == 0 else ["", part]
    return "\n".join(out + [END])


def block_in(text: str) -> str:
    start = text.index(BEGIN)
    return text[start:text.index(END, start) + len(END)]


# a router handing to two skills through a decision, one of them a gate, both handing to lab-c
MAP = fenced(
    "flowchart LR",
    "IN(a request):::entry --> lab-router:::work",
    "lab-router --> KIND{kind}:::decision",
    "KIND -->|a| lab-a:::work",
    "KIND -->|b| lab-b:::gate",
    "lab-a --> lab-c:::work",
    "lab-b --> lab-c",
)
BODY = f"Does the thing.\n\n{CALL} when the person names it.\n\n## Done when\n\n- it is done\n"


class SyncCase(TempDirCase):
    def brain(self, docs=None, meta=None, names=(), bodies=None, role=None, prefix="lab", extra=None) -> Path:
        """A brain whose skills and maps are exactly the ones given. Whatever `fake_brain` copied from the
        working tree (shipped brain-* skills, the shipped meta map) is removed first, so no test here
        depends on, or counts, a skill it did not create."""
        root = self.fake_brain(prefix=prefix, role=role, extra=extra)
        shutil.rmtree(str(root / ".claude" / "skills"), ignore_errors=True)
        shipped_meta_map = root / "_meta" / "ROUTING-META.md"
        if shipped_meta_map.exists():
            shipped_meta_map.unlink()
        if docs is not None:
            (root / "docs").mkdir(exist_ok=True)
            (root / "docs" / "ROUTING.md").write_text(docs, encoding="utf-8")
        if meta is not None:
            (root / "_meta" / "ROUTING-META.md").write_text(meta, encoding="utf-8")
        for name in names:
            self.make_skill(root, name, "Does X. Use when Y.", BODY)
        for name, body in (bodies or {}).items():
            self.make_skill(root, name, "Does X. Use when Y.", body)
        return root

    @staticmethod
    def cfg(root: Path) -> config.Config:
        return config.load(root)

    def sync(self, root: Path, check: bool = False, problems=None) -> list:
        return routing_sync.sync(root, self.cfg(root), check, problems)

    @staticmethod
    def skill_text(root: Path, name: str) -> str:
        return (root / ".claude" / "skills" / name / "SKILL.md").read_text(encoding="utf-8")

    def block_of(self, root: Path, name: str) -> str:
        return block_in(self.skill_text(root, name))

    @staticmethod
    def rel(name: str) -> str:
        return f".claude/skills/{name}/SKILL.md"

    @staticmethod
    def lint_routing(root: Path) -> list:
        return routing.lint_routing(root, config.load(root), skills.list_skills(root))



"""`routing sync`: write each skill's `## Where this sits` block from the routing map (spec §7.7).

The block sits between generated markers and says what runs before a skill, what it hands to, whether it
is a gate, and which paths the gate reserves for it. It is generated because hand-written sequence lines
drift the first time an edge moves. The `**Call it directly when:**` line is written by hand, outside the
markers; `sync` only adds a `TODO` one where there is none, which `lint` reports as a gap.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Callable, Dict, Iterable, List, Optional, Set, Tuple

from . import gate, routing
from .config import Config
from .report import BROKEN, Finding
from .skills import list_skills, owned_skills, parse_frontmatter

BEGIN = "<!-- where:begin — generated by _meta/brain routing sync; do not edit -->"
END = "<!-- where:end -->"
HEADING = "## Where this sits"
CALL = routing.CALL  # the line lint looks for; one string, so sync and lint cannot disagree about it
TODO = "**Call it directly when:** TODO — say when someone should call this directly, and which earlier steps still apply."

_SUMMARY = "routing sync"  # the subject of a finding that is about the run, not about a file

GATE_NOTICE = ("**A gate on its path:** it runs every time, in any order with the other gates, including when it "
               "comes back clean. Record its result either way.")
NO_PREDECESSOR = "nothing — an entry point into the tree."
NO_SUCCESSOR = "nothing — a person takes it from here."
NOT_PLACED = "nobody has placed it yet."

# One `classDef` line per class of the map's dialect, so authors only write `:::gate`. Neutral fills with a
# dark text colour: the same lines read on a light and a dark page.
CLASS_STYLES: Dict[str, str] = {
    "entry": "classDef entry fill:#e8eef7,stroke:#5b7aa6,color:#1f2328;",
    "gate": "classDef gate fill:#fbf1d3,stroke:#b08a1e,color:#1f2328;",
    "work": "classDef work fill:#eceff3,stroke:#6b7686,color:#1f2328;",
    "optional": "classDef optional fill:#f5f5f5,stroke:#8c8c8c,stroke-dasharray:4 3,color:#1f2328;",
    "decision": "classDef decision fill:#efe8f6,stroke:#8061a8,color:#1f2328;",
    "state": "classDef state fill:#e5f1e8,stroke:#5a8a68,color:#1f2328;",
    "human": "classDef human fill:#f8e6e6,stroke:#a86060,color:#1f2328;",
}


# -- the block -----------------------------------------------------------------------------------


def _names(names: Iterable[str]) -> str:
    return " · ".join(f"`{name}`" for name in sorted(names))


def render_block(skill: str, up: Set[str], down: Set[str], is_gate: bool, reserved: List[Tuple[str, bool]],
                 not_drawn: Optional[str], drawn: bool) -> str:
    """The generated block for `skill`, markers included, with no trailing newline: one paragraph per line
    below, a blank line apart so that it renders as lines and not as one run-on sentence.

    `up` and `down` are the skills that hand to it and that it hands to (a skill is never its own
    neighbour). `reserved` is (glob, spend_on_revision) for each path a gate reserves for it. A skill that
    is not `drawn` gets `not_drawn` (the reason its row under `## Not drawn` gives, None when it has no row)
    in place of the two sequence lines.
    """
    lines: List[str] = []
    if drawn:
        before, after = set(up) - {skill}, set(down) - {skill}
        lines.append("**Runs after:** " + (_names(before) if before else NO_PREDECESSOR))
        lines.append("**Hand to next:** " + (_names(after) if after else NO_SUCCESSOR))
    else:
        why = NOT_PLACED if not_drawn is None else (" ".join(not_drawn.split()) or "no reason given.")
        lines.append("**Not in the routing map:** " + why)
    if is_gate:
        lines.append(GATE_NOTICE)
    for glob, spend_on_revision in reserved:
        tail = "; each revision needs a fresh run." if spend_on_revision else "."
        lines.append(f"**Reserved output:** writing `{glob}` needs this skill to have run{tail}")
    return "\n".join([BEGIN, "\n\n".join(lines), END])


# -- placing a block in a skill's text -----------------------------------------------------------
#
# A SKILL.md is edited as a list of lines split on "\n" only, so a CRLF file keeps its carriage returns
# and the rest of the file is never re-encoded or re-flowed.


def _fence_mask(lines: List[str]) -> List[bool]:
    """For each line, whether it is a code fence or inside one. Markers and headings shown inside a fence are
    documentation, not structure."""
    mask: List[bool] = []
    open_ticks = 0
    for line in lines:
        text = line.rstrip("\r")
        if open_ticks:
            mask.append(True)
            closing = routing._FENCE_CLOSE.fullmatch(text)
            if closing and len(closing.group(1)) >= open_ticks:
                open_ticks = 0
            continue
        opening = routing._FENCE_OPEN.fullmatch(text)
        mask.append(bool(opening))
        if opening:
            open_ticks = len(opening.group(1))
    return mask


def _find(lines: List[str], mask: List[bool], start: int, marker: str, after: int = -1) -> Optional[int]:
    """The first line from `start` (and past `after`) that is `marker` on its own, outside a code fence."""
    for index in range(max(start, after + 1), len(lines)):
        if not mask[index] and lines[index].rstrip() == marker:
            return index
    return None


def _markers(lines: List[str], start: int) -> Optional[Tuple[int, int]]:
    """(begin, end) line numbers of the generated block, None when the text has none. A begin marker with no
    end after it is an error: guessing where the block stops could delete what a person wrote."""
    mask = _fence_mask(lines)
    begin = _find(lines, mask, start, BEGIN)
    if begin is None:
        return None
    end = _find(lines, mask, start, END, after=begin)
    if end is None:
        raise ValueError(f"has a '{BEGIN}' marker with no '{END}' after it; remove or finish the marker and "
                         f"run sync again")
    return begin, end


def _insert(lines: List[str], at: int, chunk: List[str], cr: str) -> None:
    """Put `chunk` before line `at`, with a blank line between it and any text on either side."""
    before = [cr] if at > 0 and lines[at - 1].strip() else []
    after = [cr] if at < len(lines) and lines[at].strip() else []
    lines[at:at] = before + chunk + after


def apply_block(text: str, block: str) -> str:
    """`text` (a SKILL.md) with `block` in it.

    The generated block, markers included, replaces what is between the markers when they are there. Else it
    goes directly under an existing `## Where this sits` heading. Else the heading and the block go before
    the body's first `## ` heading, or at the end of the body when it has none. Nothing outside the frontmatter
    and code fences counts: those are skipped. When the body has no `**Call it directly when:**` line, a
    `TODO` one is added under the block. Raises ValueError for a begin marker with no end marker.
    """
    cr = "\r" if "\r\n" in text else ""
    chunk = [line + cr for line in block.split("\n")]
    lines = text.split("\n")
    body = parse_frontmatter(text)[1]
    start = text[:len(text) - len(body)].count("\n")  # the body is a suffix of the text
    found = _markers(lines, start)
    if found:
        lines[found[0]:found[1] + 1] = chunk
    else:
        mask = _fence_mask(lines)
        heading = _find(lines, mask, start, HEADING)
        first_section = next((i for i in range(start, len(lines)) if not mask[i] and lines[i].startswith("## ")),
                             None)
        if heading is not None:
            _insert(lines, heading + 1, chunk, cr)
        elif first_section is not None:
            _insert(lines, first_section, [HEADING + cr, cr] + chunk, cr)
        else:  # the end of the body, ending the file with one newline
            while len(lines) > start and not lines[-1].strip():
                lines.pop()
            lines += ([cr] if len(lines) > start else []) + [HEADING + cr, cr] + chunk + [""]
    placed = _markers(lines, start)
    if placed is None:  # the only way a block we just wrote is not found: a code fence that is never closed
        raise ValueError("has a code fence that is never closed, which hides where the block goes; close it "
                         "and run sync again")
    if routing._call_line(parse_frontmatter("\n".join(lines))[1]) == "missing":
        _insert(lines, placed[1] + 1, [TODO + cr], cr)
    return "\n".join(lines)


# -- the styles of the map -----------------------------------------------------------------------

_CLASSDEF_NAMES = re.compile(r"classDef[ \t]+([A-Za-z][A-Za-z0-9_,-]*)[ \t]+\S")  # the names are comma-separated


def _diagram_fences(lines: List[str]) -> List[Tuple[Optional[int], Set[str], Set[str]]]:
    """For each mermaid fence the parser would read: (the line of its `flowchart` header or None, the classes
    its nodes use, the classes it already defines). Fences and comments are read as `routing.parse` reads them."""
    found: List[Tuple[Optional[int], Set[str], Set[str]]] = []
    fence: Optional[Tuple[int, bool]] = None
    header: Optional[int] = None
    used: Set[str] = set()
    defined: Set[str] = set()
    in_comment = False
    for number, raw in enumerate(lines):
        raw = raw.rstrip("\r")
        if number == 0 and raw.startswith("\ufeff"):
            raw = raw[1:]
        if fence is not None:
            closing = routing._FENCE_CLOSE.fullmatch(raw)
            if closing and len(closing.group(1)) >= fence[0]:
                if fence[1]:
                    found.append((header, used, defined))
                fence = None
            elif fence[1]:
                line = raw.strip()
                if header is None and routing._HEADER.fullmatch(line):
                    header = number
                elif _CLASSDEF_NAMES.match(line):
                    defined.update(_CLASSDEF_NAMES.match(line).group(1).split(","))
                elif line and not line.startswith("%%") and not routing._HEADER.fullmatch(line):
                    try:
                        refs, _links = routing._scan_statement(line)
                    except routing._Unsupported:
                        continue  # lint reports the line; it has no class to style
                    used.update(ref.cls for ref in refs if ref.cls)
            continue
        visible, in_comment, _opened = routing._strip_comments(raw, in_comment)
        opening = routing._FENCE_OPEN.fullmatch(visible)
        if opening:
            fence = (len(opening.group(1)), opening.group(2) == "mermaid")
            header, used, defined = None, set(), set()
    if fence is not None and fence[1]:  # a fence the file ends inside is still read
        found.append((header, used, defined))
    return found


def style_map(text: str) -> str:
    """`text` with a `classDef` line added for each class a mermaid fence uses and does not define, right
    after that fence's `flowchart` line, in the order of `routing.CLASSES`. A class that already has a
    definition is left as written, so is a class with no style here, and so is a fence with no header."""
    lines = text.split("\n")
    for header, used, defined in reversed(_diagram_fences(lines)):
        if header is None:
            continue
        missing = [cls for cls in CLASS_STYLES if cls in used and cls not in defined]
        if not missing:
            continue
        indent = lines[header][:len(lines[header]) - len(lines[header].lstrip())]
        cr = "\r" if lines[header].endswith("\r") else ""
        lines[header + 1:header + 1] = [indent + CLASS_STYLES[cls] + cr for cls in missing]
    return "\n".join(lines)


# -- the command ---------------------------------------------------------------------------------


def _reserved(rules: List[gate.Rule], skill: str) -> List[Tuple[str, bool]]:
    """(glob, spend_on_revision) for each path a gate rule reserves for `skill`, by glob. Two rules on one
    glob are both in force, so the stricter one is told."""
    spend: Dict[str, bool] = {}
    for rule in rules:
        if skill in rule.skills:
            spend[rule.path] = spend.get(rule.path, False) or rule.spend_on_revision
    return sorted(spend.items())


def _update(root: Path, rel: str, transform: Callable[[str], str], check: bool,
            refused: List[Finding]) -> bool:
    """Apply `transform` to the text of `rel`; write it back unless `check`. True when the text differs.

    A file that is not there is left alone. One that is not UTF-8, cannot be written, or that `transform`
    refuses is left untouched and becomes a finding in `refused`: rewriting it could lose what is in it.
    """
    path = root / rel
    try:
        with open(str(path), encoding="utf-8", newline="") as handle:  # newline="": CRLF stays CRLF
            text = handle.read()
    except FileNotFoundError:
        return False
    except UnicodeDecodeError:
        refused.append(Finding(BROKEN, rel, "is not UTF-8 text, so it was left as it is"))
        return False
    except OSError as why:
        refused.append(Finding(BROKEN, rel, f"cannot be read ({why.strerror or why})"))
        return False
    try:
        updated = transform(text)
    except ValueError as why:
        refused.append(Finding(BROKEN, rel, f"{why}"))
        return False
    if updated == text:
        return False
    if not check:
        try:
            with open(str(path), "w", encoding="utf-8", newline="") as handle:
                handle.write(updated)
        except OSError as why:
            refused.append(Finding(BROKEN, rel, f"cannot be written ({why.strerror or why})"))
            return False
    return True


class SyncRefused(Exception):
    """`sync` could not look at, or could not write, something, and the caller gave no `problems` list to
    collect that in. `findings` are the BROKEN findings (the same ones the command prints), `changed` the paths
    that were written before the refusal (empty when the map or the gate rules were refused, which writes nothing)."""

    def __init__(self, findings: List[Finding], changed: List[str]) -> None:
        self.findings = list(findings)
        self.changed = list(changed)
        super().__init__("routing sync refused: " + "; ".join(f"{f.subject}: {f.message}" for f in self.findings))


def refused_paths(findings: Iterable[Finding]) -> List[str]:
    """The files `findings` name, once each in order: a subject loses its `:line`, and the summary finding
    (which names no file) is left out."""
    found: List[str] = []
    for finding in findings:
        path = re.sub(r":\d+$", "", finding.subject)
        if finding.subject != _SUMMARY and path not in found:
            found.append(path)
    return found


def _sync(root: Path, cfg: Config, check: bool) -> Tuple[List[str], List[Finding]]:
    """(the paths changed or, with `check`, stale; the refusals)."""
    graph = routing.load_graph(root)
    if graph.problems:
        summary = Finding(BROKEN, _SUMMARY, "the routing map has problems, so nothing was changed; fix them "
                                            "(see lint) and run it again")
        return [], graph.problems + [summary]
    try:
        rules, _exempt = gate.load_rules(root, cfg)
    except ValueError as why:
        return [], [Finding(BROKEN, f"_meta/{gate.GATES_FILE}", f"{why}; nothing was changed")]
    up, down = routing.contract(graph)
    changed: List[str] = []
    refused: List[Finding] = []
    maps = ["docs/ROUTING.md"] + (["_meta/ROUTING-META.md"] if cfg.role == "template" else [])
    for rel in maps:
        if _update(root, rel, style_map, check, refused):
            changed.append(rel)
    for skill in owned_skills(cfg, list_skills(root)):
        node = graph.nodes.get(skill.name)
        block = render_block(skill.name, up.get(skill.name, set()), down.get(skill.name, set()),
                             node is not None and node.cls == "gate", _reserved(rules, skill.name),
                             graph.not_drawn.get(skill.name), node is not None)
        rel = skill.path.relative_to(root).as_posix()
        if _update(root, rel, lambda text, block=block: apply_block(text, block), check, refused):
            changed.append(rel)
    return changed, refused


def sync(root: Path, cfg: Config, check: bool, problems: Optional[List[Finding]] = None) -> List[str]:
    """Write the `## Where this sits` block of every skill this brain owns, and the `classDef` lines of the
    maps (`docs/ROUTING.md`, and `_meta/ROUTING-META.md` in the template).

    A map that has problems (unreadable, an unclosed comment, a line outside the dialect) or unreadable gate
    rules would make every block wrong, so then nothing is written. A skill that is not UTF-8, cannot be
    read or written, has a begin marker with no end marker, or has a code fence that is never closed is left
    as it is and the rest are still done. Each of these is a BROKEN refusal.

    A refusal cannot be missed:
    - `check` (writes nothing): the result is every path that is out of date **and** every file that could not
      be confirmed current (the map or the gate rules for a whole-run refusal, the skill for a file one), so an
      empty result means everything was looked at and is current. Any caller may read just that.
    - not `check`, `problems` given: the result is the paths written, and each refusal is appended to
      `problems`; the caller chose to read them there.
    - not `check`, no `problems`: SyncRefused is raised after the rest is done, carrying the findings and the
      paths written.
    `problems` is also filled when `check` is set.
    """
    changed, refused = _sync(Path(root), cfg, check)
    if problems is not None:
        problems.extend(refused)
    if check:
        return changed + [path for path in refused_paths(refused) if path not in changed]
    if refused and problems is None:
        raise SyncRefused(refused, changed)
    return changed

"""`brain practices`: the store of worked-out facts in `docs/practices/` (spec §7.4).

One file per fact, `kebab-case-id.md`, with a frontmatter block this module lints, an `INDEX.md` it
generates, and lookups (`candidates` for likely duplicates, `search` for the entry you need).
Findings never repeat a field's value (only a well-formed id), so a stray secret in an entry is
not echoed to a terminal or log.
"""
from __future__ import annotations

import os
import re
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import List, Optional, Tuple

from . import config, paths
from .config import Config
from .report import BLOCK, OK, WARN, Finding, emit, exit_code
from .skills import parse_frontmatter

REQUIRED = ("id", "tags", "durability", "evidence", "verified", "source", "reviewed-against")
# Field -> the condition that makes it required.
CONDITIONAL = {"recheck": "durability == volatile", "reproduced-by": "evidence in (reproduced, reliable)"}
# Builder addition: what "supersede, never delete" writes on the old entry; it must resolve.
OPTIONAL = ("superseded-by",)

DURABILITY = ("durable", "volatile")
EVIDENCE = ("researched", "reproduced", "reliable")

PRACTICES_DIR = ("docs", "practices")
INDEX_FILE = "INDEX.md"
NOT_ENTRIES = ("README.md", INDEX_FILE)
INDEX_HEADER = "<!-- generated by _meta/brain practices index; do not edit -->"

TAG_WEIGHT = 0.6
WORD_WEIGHT = 0.4

_KEBAB = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
_DATE = re.compile(r"([0-9]{4})-([0-9]{2})-([0-9]{2})")
_REPRODUCED_BY = re.compile(r"(.+),[ \t]*([0-9]{4}-[0-9]{2}-[0-9]{2})")
_LINK = re.compile(r"\[\[([^\[\]\n]+)\]\]")
_FENCE = re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1[^\n]*$", re.MULTILINE | re.DOTALL)
_INLINE_CODE = re.compile(r"`[^`\n]*`")
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+")
_LIST_MARKER = re.compile(r"^(?:[-*+>][ \t]+)+")
_WORD = re.compile(r"[a-z0-9]+")

# Words that say nothing about what a practice is about; left out of the word overlap.
STOPWORDS = frozenset(
    """a about above after again against all also am an and any are as at be because been before being
    below between both but by can could did do does doing down during each etc few for from further had
    has have having he her here him his how i if in into is it its just may me might more most must my
    no nor not of off on once only or other our out over own per same shall she should so some such
    than that the their them then there these they this those through to too under until up us very via
    was we were what when where which while who why will with would you your""".split()
)


@dataclass
class Entry:
    """One practice. `id` is the file name without `.md` (what `[[id]]` links and `reviewed-against`
    name); lint holds the frontmatter `id`, kept in `meta`, equal to it. `meta` values are raw strings."""

    id: str
    path: Path
    meta: dict[str, str]
    body: str


# -- reading -----------------------------------------------------------------------


def practices_dir(root: Path) -> Path:
    return Path(root).joinpath(*PRACTICES_DIR)


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""  # lint then reports the missing frontmatter


def load_entries(root: Path) -> List[Entry]:
    """Every `docs/practices/*.md` except `README.md` and `INDEX.md`, sorted by file name."""
    base = practices_dir(root)
    try:
        files = sorted(
            p for p in base.iterdir()
            if p.suffix == ".md" and not p.name.startswith(".") and p.name not in NOT_ENTRIES and p.is_file()
        )
    except OSError:
        return []
    found = []
    for path in files:
        meta, body = parse_frontmatter(_read(path))
        found.append(Entry(path.stem, path, meta, body))
    return found


def _strip_quotes(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_list(value: Optional[str]) -> Optional[List[str]]:
    """`[a, b]` as ['a', 'b'] (blank items dropped, matching quotes removed); None when `value` is not bracketed."""
    if value is None:
        return None
    text = value.strip()
    if not (text.startswith("[") and text.endswith("]")):
        return None
    items = [_strip_quotes(item.strip()) for item in text[1:-1].split(",")]
    return [item for item in items if item]


def parse_date(value: Optional[str]) -> Optional[date]:
    """A strict `YYYY-MM-DD` as a date, else None (the same on every Python version)."""
    match = _DATE.fullmatch((value or "").strip())
    if not match:
        return None
    try:
        return date(int(match.group(1)), int(match.group(2)), int(match.group(3)))
    except ValueError:
        return None


def point(entry: Entry) -> str:
    """The entry's first sentence: the first paragraph of the body, headings skipped."""
    paragraph: List[str] = []
    for line in entry.body.split("\n"):
        line = line.strip()
        if not line:
            if paragraph:
                break
            continue
        if line.startswith("#") and not paragraph:
            continue
        paragraph.append(line)
    text = _LIST_MARKER.sub("", " ".join(paragraph))
    return _SENTENCE_END.split(text, 1)[0].strip()


# -- lint --------------------------------------------------------------------------


def _shown(name: str) -> str:
    """A name to put in a message: itself when it is shaped like an id, else a placeholder."""
    return name if _KEBAB.fullmatch(name) else "<not an id>"


def _links(body: str) -> List[str]:
    """The `[[id]]` targets in `body` outside code, once each, in order of appearance."""
    text = _INLINE_CODE.sub("", _FENCE.sub("", body))
    found: List[str] = []
    for match in _LINK.finditer(text):
        target = match.group(1).strip()
        if target not in found:
            found.append(target)
    return found


def _subject(root: Path, entry: Entry) -> str:
    try:
        return entry.path.relative_to(Path(root)).as_posix()
    except ValueError:
        return entry.path.as_posix()


def _stale_since(entry: Entry, cfg: Config, today: date) -> Optional[date]:
    """The `verified` date when the entry is stale: older than `stale_after_days` and not superseded."""
    if entry.meta.get("superseded-by"):
        return None  # retired, not forgotten: nothing left to re-verify
    verified = parse_date(entry.meta.get("verified"))
    if verified is not None and (today - verified).days > cfg.stale_after_days:
        return verified
    return None


def _check(entry: Entry, known: set, cfg: Config, today: date) -> List[Tuple[str, str]]:
    meta = entry.meta
    if not meta:
        return [(BLOCK, "no frontmatter: the file must start with a --- block of fields")]
    problems: List[Tuple[str, str]] = []

    def block(message: str) -> None:
        problems.append((BLOCK, message))

    def need(name: str) -> Optional[str]:
        value = meta.get(name, "")
        if not value:
            block(f"missing required field: {name}")
            return None
        return value

    value = need("id")
    if value is not None:
        if value != entry.id:
            block(f"id must equal the file name ({entry.id})")
        elif not _KEBAB.fullmatch(value):
            block("id must be kebab-case: lowercase letters and digits joined by single hyphens")

    value = need("tags")
    if value is not None and not parse_list(value):
        block("tags must be a [list] with at least one tag")

    durability = need("durability")
    if durability is not None and durability not in DURABILITY:
        block("durability must be one of " + ", ".join(DURABILITY))
        durability = None

    evidence = need("evidence")
    if evidence is not None and evidence not in EVIDENCE:
        block("evidence must be one of " + ", ".join(EVIDENCE))
        evidence = None

    verified = None
    value = need("verified")
    if value is not None:
        verified = parse_date(value)
        if verified is None:
            block("verified must be a valid YYYY-MM-DD date")
        elif verified > today:
            block("verified is in the future")

    value = need("source")
    if value is not None and evidence == "reliable":
        if len([part for part in value.split(",") if part.strip()]) < 2:
            block("source needs 2 or more comma-separated entries at evidence reliable")

    if durability == "volatile" and not meta.get("recheck"):
        block("recheck is required when durability is volatile")

    if evidence in ("reproduced", "reliable"):
        value = meta.get("reproduced-by")
        if not value:
            block("reproduced-by is required when evidence is reproduced or reliable")
        else:
            match = _REPRODUCED_BY.fullmatch(value)
            day = parse_date(match.group(2)) if match else None
            if day is None:
                block('reproduced-by must end with ", YYYY-MM-DD" (a real date)')
            elif day > today:
                block("reproduced-by date is in the future")

    value = need("reviewed-against")
    if value is not None:
        reviewed = parse_list(value)
        if reviewed is None:
            block("reviewed-against must be a [list] of ids ([] when nothing was close)")
        else:
            for other in reviewed:
                if other not in known:
                    block(f"reviewed-against names a missing entry: {_shown(other)}")

    value = meta.get("superseded-by")
    if value:
        successors = parse_list(value)
        for other in (successors if successors is not None else [value]):
            if other not in known:
                block(f"superseded-by names a missing entry: {_shown(other)}")

    for link in _links(entry.body):
        if link not in known:
            block(f"[[{_shown(link)}]] does not resolve to an entry")

    if _stale_since(entry, cfg, today) is not None:
        problems.append((
            WARN,
            f"verified {verified.isoformat()}, more than {cfg.stale_after_days} days ago; "
            "re-verify it, then update 'verified'",
        ))
    return problems


def _lint_entries(root: Path, entries: List[Entry], cfg: Config, today: date) -> List[Finding]:
    known = {entry.id for entry in entries}
    findings: List[Finding] = []
    for entry in entries:
        subject = _subject(root, entry)
        for severity, message in _check(entry, known, cfg, today):
            findings.append(Finding(severity, subject, message))
    return findings


def lint(root: Path, cfg: Config, today: date) -> List[Finding]:
    """BLOCK findings for rule breaks (spec §7.4), WARN for entries not verified within `stale_after_days`."""
    return _lint_entries(root, load_entries(root), cfg, today)


# -- the generated index -----------------------------------------------------------


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_index(entries: List[Entry], cfg: Config, today: date) -> str:
    """The text of `INDEX.md`. It depends on `today` only through which entries are stale."""
    ordered = sorted(entries, key=lambda e: e.id)
    lines = [INDEX_HEADER, "", "# Practices index", "",
             "Look facts up with `_meta/brain practices search <terms>`; a `volatile` hit names a "
             "`recheck` to run first.", "", "## Evidence", ""]
    for kind in EVIDENCE:
        lines.append(f"- {kind}: {sum(1 for e in ordered if e.meta.get('evidence') == kind)}")
    unknown = sum(1 for e in ordered if e.meta.get("evidence") not in EVIDENCE)
    if unknown:
        lines.append(f"- not recorded or unknown: {unknown}")

    stale = []
    for entry in ordered:
        since = _stale_since(entry, cfg, today)
        if since is not None:
            stale.append((since, entry.id))
    lines += ["", "## Stale", ""]
    if stale:
        lines += [f"Not verified in the last {cfg.stale_after_days} days; re-check, then update `verified`:", ""]
        lines += [f"- {entry_id} (verified {since.isoformat()})" for since, entry_id in sorted(stale)]
    else:
        lines.append("None.")

    lines += ["", "## Entries", "", "| id | evidence | durability | verified | point |", "| --- | --- | --- | --- | --- |"]
    for entry in ordered:
        cells = [entry.id, entry.meta.get("evidence", ""), entry.meta.get("durability", ""),
                 entry.meta.get("verified", ""), point(entry)]
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return "\n".join(lines) + "\n"


# -- finding things ----------------------------------------------------------------


def _words(text: str) -> set:
    return {w for w in _WORD.findall(text.lower()) if len(w) > 1 and w not in STOPWORDS}


def _jaccard(a: set, b: set) -> float:
    union = a | b
    return len(a & b) / len(union) if union else 0.0


def candidates(entries: List[Entry], tags: List[str], text: str, limit: int = 5) -> List[Tuple[str, float]]:
    """Existing entries that may duplicate a proposed one, best first: `(id, score)`, score > 0.

    score = 0.6 x tag overlap + 0.4 x word overlap (Jaccard), the words being those of the entry's
    body and of `text`, stopwords removed. Equal scores order by id.
    """
    want_tags = {t.strip().lower() for t in tags if t.strip()}
    want_words = _words(text)
    scored = []
    for entry in entries:
        have_tags = {t.lower() for t in (parse_list(entry.meta.get("tags")) or [])}
        score = TAG_WEIGHT * _jaccard(want_tags, have_tags) + WORD_WEIGHT * _jaccard(want_words, _words(entry.body))
        if score > 0:
            scored.append((entry.id, score))
    scored.sort(key=lambda pair: (-pair[1], pair[0]))
    return scored[:max(limit, 0)]


def search(entries: List[Entry], terms: List[str]) -> List[Entry]:
    """Entries holding every term (case-insensitive) in their id, tags or body, most hits first."""
    needles = [t.strip().lower() for t in terms if t.strip()]
    if not needles:
        return []
    ranked = []
    for entry in entries:
        haystack = "\n".join([entry.id, entry.meta.get("tags", ""), entry.body]).lower()
        if all(n in haystack for n in needles):
            ranked.append((sum(haystack.count(n) for n in needles), entry))
    ranked.sort(key=lambda pair: (-pair[0], pair[1].id))
    return [entry for _hits, entry in ranked]


def describe(entry: Entry) -> List[str]:
    """The lines `search` prints for a hit; a volatile entry adds the check to run first."""
    meta = entry.meta
    lines = [
        f"{entry.id}: {meta.get('evidence') or '?'}, {meta.get('durability') or '?'}, "
        f"verified {meta.get('verified') or '?'}",
        f"  {point(entry)}",
    ]
    if meta.get("durability") == "volatile":
        lines.append(f"  volatile: run {meta.get('recheck') or '(no recheck recorded)'} first")
    return lines


# -- the command -------------------------------------------------------------------


def add_arguments(parser) -> None:
    sub = parser.add_subparsers(dest="practices_command", metavar="<subcommand>", required=True)
    sub.add_parser("lint", help="check every entry against the schema (errors block, stale entries warn)",
                   description="Check every entry in docs/practices/ against the schema.")
    index = sub.add_parser("index", help="write docs/practices/INDEX.md",
                           description="Write docs/practices/INDEX.md from the entries.")
    index.add_argument("--check", action="store_true", help="write nothing; exit 1 when INDEX.md is out of date")
    cand = sub.add_parser("candidates", help="rank existing entries that may duplicate a proposed one",
                          description="Rank existing entries by tag and word overlap with a proposed one: "
                                      "give a draft FILE, or --tags and/or --text.")
    cand.add_argument("file", nargs="?", metavar="FILE", help="a draft entry to compare")
    cand.add_argument("--tags", help="comma-separated tags of the proposed entry")
    cand.add_argument("--text", help="the proposed entry's point and specifics")
    find = sub.add_parser("search", help="find entries matching every term",
                          description="Entries whose id, tags or body hold every TERM (case-insensitive).")
    find.add_argument("terms", nargs="+", metavar="TERM")


def _same_file(a: Path, b: str) -> bool:
    try:
        return os.path.samefile(str(a), b)
    except OSError:
        return False


def _run_candidates(root: Path, args) -> int:
    given_parts = args.tags is not None or args.text is not None
    if bool(args.file) == given_parts:  # both given, or neither
        print("practices candidates: give a draft FILE, or --tags and/or --text (not both)", file=sys.stderr)
        return 2
    entries = load_entries(root)
    if args.file:
        try:
            with open(args.file, encoding="utf-8", errors="replace") as handle:
                text = handle.read()
        except OSError as exc:
            print(f"practices candidates: cannot read {args.file}: {exc.strerror or exc}", file=sys.stderr)
            return 2
        meta, body = parse_frontmatter(text)
        tags = parse_list(meta.get("tags")) or []
        entries = [e for e in entries if not _same_file(e.path, args.file)]  # a draft is not its own duplicate
    else:
        tags = [t.strip() for t in (args.tags or "").split(",")]
        body = args.text or ""
    by_id = {e.id: e for e in entries}
    ranked = candidates(entries, tags, body)
    if not ranked:
        print("no candidates")
    for entry_id, score in ranked:
        print(f"{score:.2f} {entry_id}: {point(by_id[entry_id])}")
    return 0


def _run_search(root: Path, args) -> int:
    found = search(load_entries(root), args.terms)
    if not found:
        print("no practice matches: " + " ".join(args.terms))
    for entry in found:
        for line in describe(entry):
            print(line)
    return 0


def _run_index(root: Path, cfg: Config, today: date, check: bool) -> int:
    entries = load_entries(root)
    wanted = render_index(entries, cfg, today)
    path = practices_dir(root) / INDEX_FILE
    subject = "/".join(PRACTICES_DIR + (INDEX_FILE,))
    try:
        with open(path, encoding="utf-8", errors="replace", newline=None) as handle:
            current: Optional[str] = handle.read()
    except OSError:
        current = None
    if current == wanted or (check and current is None and not entries):
        emit([Finding(OK, subject, "up to date")])
        return 0
    if check:
        state = "missing" if current is None else "out of date"
        emit([Finding(BLOCK, subject, f"{state}; run _meta/brain practices index")])
        return 1
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(wanted)
    except OSError as exc:
        print(f"practices index: cannot write {subject}: {exc.strerror or exc}", file=sys.stderr)
        return 1
    emit([Finding(OK, subject, f"written ({len(entries)} entries)")])
    return 0


def run(args) -> int:
    root = paths.harness_root()
    name = args.practices_command
    if name == "search":
        return _run_search(root, args)
    if name == "candidates":
        return _run_candidates(root, args)
    try:
        cfg = config.load(root)
    except config.ConfigError as exc:
        print(f"practices: {exc}", file=sys.stderr)
        return 1
    today = date.today()
    if name == "index":
        return _run_index(root, cfg, today, args.check)
    entries = load_entries(root)
    findings = _lint_entries(root, entries, cfg, today)
    emit(findings)
    blocking = sum(1 for f in findings if f.severity == BLOCK)
    stale = sum(1 for f in findings if f.severity == WARN)
    print(f"practices lint: {len(entries)} checked, {blocking} blocking, {stale} stale")
    return exit_code(findings)

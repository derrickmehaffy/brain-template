class ReadmeTest(PracticesCase):
    def readme(self) -> str:
        return README.read_text(encoding="utf-8")

    def test_readme_example_passes_lint(self):
        section = self.readme().split("\n## Example", 1)[1]
        block = re.search(r"```markdown\n(.*?)\n```", section, re.DOTALL)
        self.assertIsNotNone(block, "## Example must hold a ```markdown block")
        text = block.group(1) + "\n"
        meta, _body = skills.parse_frontmatter(text)
        self.write(meta["id"], text)
        self.assertEqual(self.lint(), [])

    def schema_keys(self) -> set:
        section = self.readme().split("\n## Schema", 1)[1].split("\n## ", 1)[0]
        block = re.search(r"```yaml\n(.*?)\n```", section, re.DOTALL)
        self.assertIsNotNone(block, "## Schema must hold a ```yaml block")
        return set(re.findall(r"^([a-z][a-z-]*):", block.group(1), re.MULTILINE))

    def test_readme_names_every_field(self):
        wanted = set(practices.REQUIRED) | set(practices.CONDITIONAL) | set(practices.OPTIONAL)
        keys = self.schema_keys()
        self.assertEqual(wanted - keys, set(), "the linter enforces fields the README does not document")
        self.assertEqual(keys - wanted, set(), "the README documents fields the linter does not know")


class LintTest(PracticesCase):
    def one_finding(self, findings):
        self.assertEqual(len(findings), 1, [(f.severity, f.message) for f in findings])
        return findings[0]

    def test_valid_entry_has_no_findings(self):
        self.write("dns-ttl", entry_text())
        self.assertEqual(self.lint(), [])

    def test_each_required_field_missing(self):
        for field in practices.REQUIRED:
            with self.subTest(field=field):
                for path in self.dir.glob("*.md"):
                    path.unlink()
                self.write("dns-ttl", entry_text({field: None}))
                finding = self.one_finding(self.lint())
                self.assertEqual((finding.severity, finding.subject), (BLOCK, "docs/practices/dns-ttl.md"))
                self.assertIn(f"missing required field: {field}", finding.message)

    def test_an_empty_value_counts_as_missing(self):
        self.write("dns-ttl", entry_text({"source": ""}))
        finding = self.one_finding(self.lint())
        self.assertEqual(finding.severity, BLOCK)
        self.assertIn("missing required field: source", finding.message)

    def test_rules(self):
        cases = [
            ("id differs from the filename", {"id": "other-name"}, BODY, "id must equal the file name"),
            ("volatile without recheck", {"recheck": None}, BODY, "recheck is required"),
            ("volatile with an empty recheck", {"recheck": ""}, BODY, "recheck is required"),
            ("reliable with one source", {"source": "resolver docs"}, BODY, "2 or more"),
            ("reliable with a blank second source", {"source": "resolver docs, "}, BODY, "2 or more"),
            ("reproduced without reproduced-by",
             {"evidence": "reproduced", "reproduced-by": None}, BODY, "reproduced-by is required"),
            ("reliable without reproduced-by", {"reproduced-by": None}, BODY, "reproduced-by is required"),
            ("reproduced-by without a date",
             {"reproduced-by": "watched the TTL count down"}, BODY, "reproduced-by must end with"),
            ("reproduced-by with only a date", {"reproduced-by": "2026-09-30"}, BODY, "reproduced-by must end with"),
            ("reproduced-by with a bad date",
             {"reproduced-by": "watched it, 2026-02-30"}, BODY, "reproduced-by must end with"),
            ("reproduced-by dated in the future",
             {"reproduced-by": "watched it, 2026-11-03"}, BODY, "reproduced-by date is in the future"),
            ("bad date", {"verified": "2026-13-45"}, BODY, "verified must be a valid YYYY-MM-DD date"),
            ("date in words", {"verified": "yesterday"}, BODY, "verified must be a valid YYYY-MM-DD date"),
            ("date without zero padding", {"verified": "2026-1-5"}, BODY, "verified must be a valid YYYY-MM-DD date"),
            ("future date", {"verified": "2026-11-03"}, BODY, "verified is in the future"),
            ("unknown evidence", {"evidence": "guessed"}, BODY, "evidence must be one of researched, reproduced, reliable"),
            ("unknown durability", {"durability": "forever"}, BODY, "durability must be one of durable, volatile"),
            ("empty tags", {"tags": "[]"}, BODY, "tags must be a [list]"),
            ("tags that are only blanks", {"tags": "[ , ]"}, BODY, "tags must be a [list]"),
            ("tags not a list", {"tags": "dns"}, BODY, "tags must be a [list]"),
            ("reviewed-against names a missing id",
             {"reviewed-against": "[no-such-entry]"}, BODY, "reviewed-against names a missing entry: no-such-entry"),
            ("reviewed-against not a list", {"reviewed-against": "none"}, BODY, "reviewed-against must be a [list]"),
            ("unresolved [[link]]", {}, "See [[no-such-entry]] for more.\n", "[[no-such-entry]] does not resolve"),
            ("unresolved superseded-by",
             {"superseded-by": "no-such-entry"}, BODY, "superseded-by names a missing entry: no-such-entry"),
        ]
        for label, over, body, needle in cases:
            with self.subTest(label):
                for path in self.dir.glob("*.md"):
                    path.unlink()
                self.write("dns-ttl", entry_text(over, body))
                finding = self.one_finding(self.lint())
                self.assertEqual((finding.severity, finding.subject), (BLOCK, "docs/practices/dns-ttl.md"))
                self.assertIn(needle, finding.message)

    def test_rules_that_hold(self):
        self.write("other", entry_text({"id": "other"}))
        cases = [
            ("durable needs no recheck", {"durability": "durable", "recheck": None}, BODY),
            ("researched needs no reproduced-by", {"evidence": "researched", "reproduced-by": None}, BODY),
            ("reproduced takes one source", {"evidence": "reproduced", "source": "one thing"}, BODY),
            ("reviewed-against an existing id", {"reviewed-against": "[other]"}, BODY),
            ("reviewed-against several ids", {"reviewed-against": "[other, dns-ttl]"}, BODY),
            ("superseded-by an existing id", {"superseded-by": "other"}, BODY),
            ("a [[link]] that resolves", {}, "See [[other]] and [[dns-ttl]].\n"),
            ("a [[link]] in a code span", {}, "Write links as `[[no-such-entry]]`.\n"),
            ("a [[link]] in a code fence", {}, "Example:\n\n```\n[[no-such-entry]]\n```\n"),
            ("verified today", {"verified": "2026-11-02"}, BODY),
            ("unknown extra fields ignored", {"note": "free text"}, BODY),
        ]
        for label, over, body in cases:
            with self.subTest(label):
                self.write("dns-ttl", entry_text(over, body))
                self.assertEqual(self.lint(), [])

    def test_id_must_be_kebab_case(self):
        self.write("Dns_TTL", entry_text({"id": "Dns_TTL"}))
        finding = self.one_finding(self.lint())
        self.assertEqual((finding.severity, finding.subject), (BLOCK, "docs/practices/Dns_TTL.md"))
        self.assertIn("id must be kebab-case", finding.message)

    def test_file_without_frontmatter_blocks_once(self):
        self.write("dns-ttl", "Just prose, no frontmatter.\n")
        finding = self.one_finding(self.lint())
        self.assertEqual((finding.severity, finding.subject), (BLOCK, "docs/practices/dns-ttl.md"))
        self.assertIn("frontmatter", finding.message)

    def test_non_utf8_entry_does_not_crash(self):
        path = self.dir / "dns-ttl.md"
        path.write_bytes(entry_text().encode("utf-8") + "\n caf\xe9 \x93x\x94\n".encode("latin-1"))
